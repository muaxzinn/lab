/**
 * Filter simulation items by category and optional query string.
 */
export function filterSimulations(
  items: SimulationItem[],
  category: SimulationCategory,
  query = ""
): SimulationItem[] {
  const normalizedQuery = query.trim().toLowerCase();

  return items.filter((item) => {
    // Category match
    const categoryMatch = category === "all" || item.category === category;
    if (!categoryMatch) return false;

    // Query match
    if (!normalizedQuery) return true;

    return (
      item.title.toLowerCase().includes(normalizedQuery) ||
      item.thaiTitle.toLowerCase().includes(normalizedQuery) ||
      item.description.toLowerCase().includes(normalizedQuery) ||
      item.thaiDescription.toLowerCase().includes(normalizedQuery) ||
      item.categoryLabel.toLowerCase().includes(normalizedQuery) ||
      item.badge.toLowerCase().includes(normalizedQuery)
    );
  });
}
