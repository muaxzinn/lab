export function getElementBySymbol(symbol: string): ChemicalElement | undefined {
  const normalized = symbol.trim().toLowerCase();
  return PERIODIC_TABLE_ELEMENTS.find((el) => el.symbol.toLowerCase() === normalized);
}

export function getElementsByCategory(category: ElementCategory): ChemicalElement[] {
  return PERIODIC_TABLE_ELEMENTS.filter((el) => el.category === category);
}

export function getElementsByPeriod(period: number): ChemicalElement[] {
  return PERIODIC_TABLE_ELEMENTS.filter((el) => el.period === period);
}

export function getElementsByBlock(block: ElementBlock): ChemicalElement[] {
  return PERIODIC_TABLE_ELEMENTS.filter((el) => el.block === block);
}

export function searchElements(query: string): ChemicalElement[] {
  const q = query.trim().toLowerCase();
  if (!q) return PERIODIC_TABLE_ELEMENTS;

  return PERIODIC_TABLE_ELEMENTS.filter(
    (el) =>
      el.name.toLowerCase().includes(q) ||
      el.symbol.toLowerCase().includes(q) ||
      el.thaiName.toLowerCase().includes(q) ||
      el.atomicNumber.toString() === q ||
      el.category.toLowerCase().includes(q) ||
      el.categoryThai.includes(q)
  );
}
